"""Validate the complete functional scope; never count partial rows as parity."""

import argparse
import json
import subprocess
from collections import Counter
from pathlib import Path

GROUPS = {
    "runtime": "主链、消息与程序",
    "workspace": "项目、文件与执行目录",
    "proactive": "主动运行",
    "extension": "扩展、资源与检查",
    "models": "模型与角色",
    "delivery": "渠道与投递",
    "product": "工作台与用户功能",
    "memory": "记忆（保留现有实现）",
}
STATUSES = {"missing": "未接入", "partial": "部分接入", "aligned": "已验收"}


def render(data):
    counts = Counter(row["status"] for row in data["features"])
    lines = [
        "# Akashic 功能对齐清单",
        "",
        "<!-- Generated by scripts/check_feature_alignment.py --write. Edit akashic-features.json. -->",
        "",
        f"参考日期：{data['reference']['date']}。固定上游 "
        f"[`{data['reference']['revision'][:12]}`]"
        f"({data['reference']['repository']}/tree/{data['reference']['revision']})。",
        "",
        data["scope"],
        "",
        f"已枚举 {len(data['features'])} 个生产插件和 {len(data['additional_surfaces'])} 个跨目录面。"
        f"当前为 {counts['partial']} 项部分接入、{counts['missing']} 项未接入、"
        f"{counts['aligned']} 项整项验收。这是范围登记，不是功能完成比例。",
        "",
        data["completion_rule"],
        "",
        "执行顺序和当前落地范围见[当前状态](./current.md)；"
        "本轮项目/目录的实际验证见[功能报告](../operations/evaluations/2026-10-19-workspace-functions.md)。",
        "",
    ]
    for group, label in GROUPS.items():
        lines += [
            f"## {label}",
            "",
            "| 上游功能 | 职责 | 当前实现 | 状态与验收 |",
            "| --- | --- | --- | --- |",
        ]
        for row in data["features"]:
            if row["group"] != group:
                continue
            paths = (
                "、".join(f"[{p}](../../{p})" for p in row["kirakira_paths"])
                or "尚无提供者"
            )
            lines.append(
                f"| [{row['upstream_plugin']}]({row['upstream_url']}) "
                f"| {row['description']} | {paths} "
                f"| **{STATUSES[row['status']]}**：{row['acceptance']} |"
            )
        lines.append("")
    lines += ["## 跨目录功能面", "", "| 范围 | 状态与验收 |", "| --- | --- |"]
    for row in data["additional_surfaces"]:
        lines.append(
            f"| {row['name']} | **{STATUSES[row['status']]}**：{row['acceptance']} |"
        )
    lines += [
        "",
        "## 更新与检查",
        "",
        "`akashic-features.json` 是清单数据源，本页由它生成。新接入和整项验收要分别更新，"
        "不能因某个目录或工具同名就改成已验收。",
        "",
        "```bash",
        "uv run --frozen python -m scripts.check_feature_alignment --write",
        "uv run --frozen python -m scripts.check_feature_alignment --reference /path/to/akashic-agent",
        "```",
        "",
        "不提供 `--reference` 时也会检查本地落点、证据路径及生成文档，适合 CI；"
        "提供时再核对固定提交的生产插件集合和跨目录路径。上游 checkout 不属于运行依赖。",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference", type=Path)
    parser.add_argument(
        "--write", action="store_true", help="regenerate the Markdown inventory"
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    data = json.loads((root / "docs/status/akashic-features.json").read_text())
    rows = data["features"]
    names = [row["upstream_plugin"] for row in rows]
    assert len(names) == len(set(names)), "duplicate upstream feature"
    for row in rows:
        assert row["status"] in STATUSES
        assert row["group"] in GROUPS
        assert row["acceptance"].strip()
        assert row["upstream_entry"] == f"plugins/{row['upstream_plugin']}/plugin.py"
        for path in [*row["kirakira_paths"], *row.get("functional_evidence", [])]:
            assert (root / path).exists(), path
        if row["status"] == "aligned":
            assert row.get("evidence"), "full parity requires functional evidence"
            for path in row["evidence"]:
                assert (root / path).exists(), path
    for row in data["additional_surfaces"]:
        assert row["status"] in STATUSES and row["acceptance"].strip()
        for path in row["kirakira_paths"]:
            assert (root / path).exists(), path
    if args.reference is not None:
        paths = subprocess.check_output(
            [
                "git",
                "ls-tree",
                "-r",
                "--name-only",
                data["reference"]["revision"],
            ],
            cwd=args.reference,
            text=True,
        ).splitlines()
        actual = {
            path.split("/")[1]
            for path in paths
            if path.startswith("plugins/")
            and path.endswith("/plugin.py")
            and path.count("/") == 2
        }
        assert set(names) == actual, {
            "missing": sorted(actual - set(names)),
            "extra": sorted(set(names) - actual),
        }
        for row in data["additional_surfaces"]:
            for path in row["upstream_paths"]:
                assert any(p == path or p.startswith(path + "/") for p in paths), path
    markdown = root / "docs/status/akashic-features.md"
    rendered = render(data)
    if args.write:
        markdown.write_text(rendered)
    else:
        assert markdown.read_text() == rendered, (
            "regenerate the Markdown inventory with --write"
        )
    print(
        json.dumps(
            {
                "plugins": len(rows),
                "statuses": dict(Counter(row["status"] for row in rows)),
                "extra_surfaces": len(data["additional_surfaces"]),
                "reference": data["reference"]["revision"],
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
